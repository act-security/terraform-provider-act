package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"text/template"
)

const (
	strictServerInterface = "StrictServerInterface"
	generatedServer       = "internal/fakeapi/gen/gen.gen.go"
	unimplementedServer   = "internal/fakeapi/gen/unimplemented.gen.go"
)

var stubTemplate = template.Must(template.New("stub").Parse(`// Code generated by internal/fakeapi/cmd/unimplemented. DO NOT EDIT.

package {{ .Package }}

import (
	"context"
	"errors"
)

var ErrNotImplemented = errors.New("operation not implemented by the fake API")

type UnimplementedStrictServer struct{}
{{ range .Methods }}
func (UnimplementedStrictServer) {{ .Name }}(context.Context, {{ .Request }}) ({{ .Response }}, error) {
	return nil, ErrNotImplemented
}
{{ end }}`))

type stubMethod struct {
	Name     string
	Request  string
	Response string
}

type stubFile struct {
	Package string
	Methods []stubMethod
}

func main() {
	if err := generateUnimplementedServer(generatedServer, unimplementedServer); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generateUnimplementedServer(source, target string) error {
	stub, err := readStrictServer(source)
	if err != nil {
		return err
	}
	code, err := renderStub(stub)
	if err != nil {
		return err
	}
	return os.WriteFile(target, code, 0o600)
}

func readStrictServer(source string) (stubFile, error) {
	file, err := parser.ParseFile(token.NewFileSet(), source, nil, parser.SkipObjectResolution)
	if err != nil {
		return stubFile{}, err
	}
	iface, found := findInterface(file, strictServerInterface)
	if !found {
		return stubFile{}, fmt.Errorf("%s: no %s", source, strictServerInterface)
	}
	methods, err := stubMethodsOf(iface)
	if err != nil {
		return stubFile{}, fmt.Errorf("%s: %w", source, err)
	}
	return stubFile{Package: file.Name.Name, Methods: methods}, nil
}

func findInterface(file *ast.File, name string) (*ast.InterfaceType, bool) {
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != name {
				continue
			}
			iface, ok := typeSpec.Type.(*ast.InterfaceType)
			return iface, ok
		}
	}
	return nil, false
}

func stubMethodsOf(iface *ast.InterfaceType) ([]stubMethod, error) {
	methods := make([]stubMethod, 0, len(iface.Methods.List))
	for _, field := range iface.Methods.List {
		signature, ok := field.Type.(*ast.FuncType)
		if !ok || len(field.Names) != 1 || len(signature.Params.List) != 2 || signature.Results == nil || len(signature.Results.List) != 2 {
			return nil, errors.New("a strict server method is not (ctx, request) (response, error)")
		}
		methods = append(methods, stubMethod{
			Name:     field.Names[0].Name,
			Request:  types.ExprString(signature.Params.List[1].Type),
			Response: types.ExprString(signature.Results.List[0].Type),
		})
	}
	return methods, nil
}

func renderStub(stub stubFile) ([]byte, error) {
	var out bytes.Buffer
	if err := stubTemplate.Execute(&out, stub); err != nil {
		return nil, err
	}
	return format.Source(out.Bytes())
}
